BEGIN;
SET LOCAL TIME ZONE 'Asia/Jakarta';
SET LOCAL search_path = public;
CREATE TABLE public.bukti_bayar (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_sewa INTEGER DEFAULT NULL,
  jenis VARCHAR(30) CHECK (jenis IN ('mobil','motor')) DEFAULT 'mobil',
  id_user INTEGER DEFAULT NULL,
  file_path varchar(255) DEFAULT NULL,
  catatan text DEFAULT NULL,
  metode varchar(50) DEFAULT 'Transfer SeaBank',
  status VARCHAR(30) CHECK (status IN ('menunggu','diterima','ditolak')) DEFAULT 'menunggu',
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT timezone('Asia/Jakarta', CURRENT_TIMESTAMP)
);

CREATE TABLE public.checklist_kendaraan (
  id_checklist INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_sewa INTEGER DEFAULT NULL,
  jenis VARCHAR(30) CHECK (jenis IN ('mobil','motor')) DEFAULT 'mobil',
  tipe VARCHAR(30) CHECK (tipe IN ('keluar','kembali')) NOT NULL,
  kondisi_eksterior varchar(20) DEFAULT 'baik',
  kondisi_interior varchar(20) DEFAULT 'baik',
  kondisi_mesin varchar(20) DEFAULT 'baik',
  kondisi_ban varchar(20) DEFAULT 'baik',
  bbm_level varchar(20) DEFAULT 'penuh',
  km_odometer INTEGER DEFAULT 0,
  catatan text DEFAULT NULL,
  foto_urls text DEFAULT NULL,
  input_by INTEGER DEFAULT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT timezone('Asia/Jakarta', CURRENT_TIMESTAMP)
);

CREATE TABLE public.denda_biaya (
  id_denda INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_sewa INTEGER DEFAULT NULL,
  jenis VARCHAR(30) CHECK (jenis IN ('mobil','motor')) DEFAULT 'mobil',
  tipe_denda varchar(50) DEFAULT 'kerusakan',
  deskripsi text DEFAULT NULL,
  jumlah decimal(12,2) DEFAULT 0.00,
  input_by INTEGER DEFAULT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT timezone('Asia/Jakarta', CURRENT_TIMESTAMP)
,
  status_bayar VARCHAR(10) DEFAULT 'belum' CHECK (status_bayar IN ('belum','lunas'))
);

CREATE TABLE public.log_penyewaan (
  id_sewa INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_user INTEGER DEFAULT NULL,
  id_mobil INTEGER DEFAULT NULL,
  tanggal_sewa date DEFAULT NULL,
  tanggal_kembali date DEFAULT NULL,
  total_bayar decimal(12,2) DEFAULT NULL,
  status VARCHAR(30) CHECK (status IN ('aktif','selesai')) DEFAULT 'aktif',
  payment_status varchar(20) DEFAULT 'pending',
  payment_method varchar(30) DEFAULT 'Transfer Bank',
  addon_total decimal(12,2) DEFAULT 0.00,
  addon_detail text DEFAULT NULL,
  kode_promo varchar(30) DEFAULT NULL,
  diskon_promo decimal(12,2) DEFAULT 0.00,
  admin_confirmed INTEGER DEFAULT 0,
  agreement_accepted INTEGER DEFAULT 0,
  agreement_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NULL,
  catatan_admin text DEFAULT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT timezone('Asia/Jakarta', CURRENT_TIMESTAMP)
,
  midtrans_order_id VARCHAR(100) UNIQUE
);

CREATE TABLE public.log_sewa_motor (
  id_sewa INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_user INTEGER DEFAULT NULL,
  id_motor INTEGER DEFAULT NULL,
  tanggal_sewa date DEFAULT NULL,
  tanggal_kembali date DEFAULT NULL,
  total_bayar decimal(12,2) DEFAULT NULL,
  status VARCHAR(30) CHECK (status IN ('aktif','selesai')) DEFAULT 'aktif',
  payment_status varchar(20) DEFAULT 'pending',
  payment_method varchar(30) DEFAULT 'Transfer Bank',
  addon_total decimal(12,2) DEFAULT 0.00,
  addon_detail text DEFAULT NULL,
  kode_promo varchar(30) DEFAULT NULL,
  diskon_promo decimal(12,2) DEFAULT 0.00,
  admin_confirmed INTEGER DEFAULT 0,
  agreement_accepted INTEGER DEFAULT 0,
  agreement_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NULL,
  catatan_admin text DEFAULT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT timezone('Asia/Jakarta', CURRENT_TIMESTAMP)
,
  midtrans_order_id VARCHAR(100) UNIQUE
);

CREATE TABLE public.mobil (
  id_mobil INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nama_mobil varchar(100) NOT NULL,
  merk varchar(50) DEFAULT NULL,
  tahun INTEGER DEFAULT NULL,
  harga_sewa decimal(12,2) DEFAULT NULL,
  foto_mobil varchar(255) DEFAULT NULL,
  status varchar(20) DEFAULT 'tersedia'
,
  kapasitas INTEGER
);

CREATE TABLE public.motor (
  id_motor INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nama_motor varchar(100) NOT NULL,
  merk varchar(50) DEFAULT NULL,
  tahun INTEGER DEFAULT NULL,
  harga_sewa decimal(12,2) DEFAULT NULL,
  foto_motor varchar(255) DEFAULT NULL,
  status varchar(20) DEFAULT 'tersedia'
,
  kapasitas INTEGER
);

CREATE TABLE public.notifikasi_admin (
  id_notif INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  tipe varchar(30) DEFAULT 'pesanan_baru',
  id_sewa INTEGER DEFAULT NULL,
  jenis VARCHAR(30) CHECK (jenis IN ('mobil','motor')) DEFAULT 'mobil',
  pesan text DEFAULT NULL,
  sudah_baca INTEGER DEFAULT 0,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT timezone('Asia/Jakarta', CURRENT_TIMESTAMP)
);

CREATE TABLE public.promo_voucher (
  id_promo INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  kode varchar(30) NOT NULL,
  deskripsi varchar(255) DEFAULT NULL,
  tipe_diskon VARCHAR(30) CHECK (tipe_diskon IN ('persen','nominal')) DEFAULT 'persen',
  nilai_diskon decimal(12,2) DEFAULT 0.00,
  min_transaksi decimal(12,2) DEFAULT 0.00,
  max_penggunaan INTEGER DEFAULT 100,
  sudah_dipakai INTEGER DEFAULT 0,
  berlaku_dari date DEFAULT NULL,
  berlaku_sampai date DEFAULT NULL,
  status VARCHAR(30) CHECK (status IN ('aktif','nonaktif')) DEFAULT 'aktif',
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT timezone('Asia/Jakarta', CURRENT_TIMESTAMP)
);

CREATE TABLE public.review_kendaraan (
  id_review INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_sewa INTEGER DEFAULT NULL,
  id_user INTEGER DEFAULT NULL,
  id_kendaraan INTEGER DEFAULT NULL,
  jenis VARCHAR(30) CHECK (jenis IN ('mobil','motor')) DEFAULT 'mobil',
  rating INTEGER DEFAULT 5,
  komentar text DEFAULT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT timezone('Asia/Jakarta', CURRENT_TIMESTAMP)
);

CREATE TABLE public.tripay_transactions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_sewa INTEGER DEFAULT NULL,
  jenis VARCHAR(30) CHECK (jenis IN ('mobil','motor')) DEFAULT 'mobil',
  merchant_ref varchar(60) DEFAULT NULL,
  tripay_ref varchar(60) DEFAULT NULL,
  channel varchar(30) DEFAULT NULL,
  amount decimal(12,2) DEFAULT 0.00,
  status varchar(20) DEFAULT 'UNPAID',
  pay_code varchar(100) DEFAULT NULL,
  pay_url varchar(255) DEFAULT NULL,
  checkout_url varchar(255) DEFAULT NULL,
  expired_at INTEGER DEFAULT NULL,
  paid_at TIMESTAMP WITHOUT TIME ZONE DEFAULT NULL,
  created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT timezone('Asia/Jakarta', CURRENT_TIMESTAMP)
);

CREATE TABLE public.app_users (
  id_user INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  username varchar(50) NOT NULL,
  password varchar(255) NOT NULL,
  nama_lengkap varchar(100) DEFAULT NULL,
  role VARCHAR(30) CHECK (role IN ('admin','customer')) DEFAULT 'customer'
,
  no_hp VARCHAR(20),
  alamat TEXT,
  foto_profil VARCHAR(255)
);

CREATE TABLE public.notifikasi_customer (
  id_notif INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_user INTEGER NOT NULL, tipe VARCHAR(30) DEFAULT 'info', id_sewa INTEGER,
  jenis VARCHAR(30) DEFAULT 'mobil' CHECK (jenis IN ('mobil','motor')),
  pesan TEXT NOT NULL, url_target VARCHAR(255) DEFAULT 'riwayat_sewa.php',
  sudah_baca SMALLINT DEFAULT 0, created_at TIMESTAMP DEFAULT timezone('Asia/Jakarta', CURRENT_TIMESTAMP)
);
CREATE INDEX notifikasi_customer_user_idx ON public.notifikasi_customer (id_user);
CREATE INDEX notifikasi_customer_sewa_idx ON public.notifikasi_customer (id_sewa);
CREATE TABLE public.chat_messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_sender INTEGER NOT NULL, id_receiver INTEGER, pesan TEXT NOT NULL,
  sudah_baca SMALLINT DEFAULT 0, created_at TIMESTAMP DEFAULT timezone('Asia/Jakarta', CURRENT_TIMESTAMP)
);
CREATE TABLE public.app_sessions (
  id VARCHAR(128) PRIMARY KEY, payload TEXT NOT NULL, expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX app_sessions_expiry_idx ON public.app_sessions (expires_at);


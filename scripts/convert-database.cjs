// Run: node scripts/convert-database.cjs
// The original InfinityFree dump remains available as the MySQL backup.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'db_rentalmobil_infinityfree.sql'), 'utf8');
const rename = name => name === 'user' ? 'app_users' : name;
const clean = sql => sql.replace(/`user`/g, 'app_users').replace(/`/g, '')
  .replace(/\b(?:tinyint|int)\(\d+\)/gi, 'INTEGER')
  .replace(/\bdatetime\b/gi, 'TIMESTAMP WITHOUT TIME ZONE')
  .replace(/current_timestamp\(\)/gi, "timezone('Asia/Jakarta', CURRENT_TIMESTAMP)");
const identities = new Map([...source.matchAll(/ALTER TABLE `(\w+)`\s+MODIFY `(\w+)`[^;]*AUTO_INCREMENT[^;]*;/g)]
  .map(m => [rename(m[1]), m[2]]));
const tables = [];
const indexes = [];
for (const match of source.matchAll(/CREATE TABLE `(\w+)` \(([\s\S]*?)\) ENGINE=[^;]+;/g)) {
  const name = rename(match[1]);
  let body = clean(match[2]).replace(/^(\s*)(\w+)\s+enum\(([^)]+)\)/gmi,
    (_, space, col, values) => `${space}${col} VARCHAR(30) CHECK (${col} IN (${values}))`);
  body = body.replace(new RegExp(`(\\b${identities.get(name)}\\s+)INTEGER NOT NULL`, 'i'), '$1INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL');
  if (name === 'denda_biaya') body += ",\n  status_bayar VARCHAR(10) DEFAULT 'belum' CHECK (status_bayar IN ('belum','lunas'))\n";
  if (name === 'app_users') body += ',\n  no_hp VARCHAR(20),\n  alamat TEXT,\n  foto_profil VARCHAR(255)\n';
  if (name === 'log_penyewaan' || name === 'log_sewa_motor') body += ',\n  midtrans_order_id VARCHAR(100) UNIQUE\n';
  if (name === 'mobil' || name === 'motor') body += ',\n  kapasitas INTEGER\n';
  tables.push(`CREATE TABLE public.${name} (${body});`);
}
for (const m of source.matchAll(/ALTER TABLE `(\w+)`\s+([\s\S]*?);/g)) {
  const name = rename(m[1]);
  if (/MODIFY/.test(m[2])) continue;
  const constraints = [];
  for (const c of m[2].matchAll(/ADD (PRIMARY KEY \([^)]+\)|UNIQUE KEY `\w+` \([^)]+\)|CONSTRAINT `\w+` FOREIGN KEY \([^)]+\) REFERENCES `\w+` \([^)]+\))/g)) {
    constraints.push(clean(c[1]).replace(/UNIQUE KEY (\w+)/, 'CONSTRAINT $1 UNIQUE'));
  }
  if (constraints.length) indexes.push(`ALTER TABLE public.${name}\n  ADD ${constraints.join(',\n  ADD ')};`);
  for (const idx of m[2].matchAll(/ADD KEY `(\w+)` (\([^)]+\))/g)) {
    indexes.push(`CREATE INDEX ${name}_${idx[1]}_idx ON public.${name} ${clean(idx[2])};`);
  }
}
const data = [...source.matchAll(/INSERT INTO `[\s\S]*?;/g)].map(m => clean(m[0]));
// Create tables before loading data; install foreign keys after all rows exist.
const extra = `
CREATE TABLE public.notifikasi_customer (
  id_notif INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_user INTEGER NOT NULL, tipe VARCHAR(30) DEFAULT 'info', id_sewa INTEGER,
  jenis VARCHAR(30) DEFAULT 'mobil' CHECK (jenis IN ('mobil','motor')),
  pesan TEXT NOT NULL, url_target VARCHAR(255) DEFAULT 'riwayat_sewa.php',
  sudah_baca SMALLINT DEFAULT 0, created_at TIMESTAMP DEFAULT timezone('Asia/Jakarta', CURRENT_TIMESTAMP)
);
CREATE INDEX notifikasi_customer_user_idx ON public.notifikasi_customer (id_user);
CREATE INDEX notifikasi_customer_sewa_idx ON public.notifikasi_customer (id_sewa);
CREATE TABLE public.chat_messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_sender INTEGER NOT NULL, id_receiver INTEGER, pesan TEXT NOT NULL,
  sudah_baca SMALLINT DEFAULT 0, created_at TIMESTAMP DEFAULT timezone('Asia/Jakarta', CURRENT_TIMESTAMP)
);
CREATE TABLE public.app_sessions (
  id VARCHAR(128) PRIMARY KEY, payload TEXT NOT NULL, expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX app_sessions_expiry_idx ON public.app_sessions (expires_at);
`;
const names = [...identities.keys(), 'notifikasi_customer', 'chat_messages', 'app_sessions'];
const security = names.map(name => `ALTER TABLE public.${name} ENABLE ROW LEVEL SECURITY;\nREVOKE ALL ON TABLE public.${name} FROM anon, authenticated;`).join('\n');
const sequences = [...identities].map(([table, col]) =>
  `SELECT setval(pg_get_serial_sequence('public.${table}', '${col}'), COALESCE(MAX(${col}), 1), MAX(${col}) IS NOT NULL) FROM public.${table};\nREVOKE ALL ON SEQUENCE public.${table}_${col}_seq FROM anon, authenticated;`).join('\n');
const output = `-- PostgreSQL / Supabase: impor SEKALI ke schema public yang kosong.
-- Sumber: db_rentalmobil_infinityfree.sql. Data, ID, dan hash password dipertahankan.
-- Tabel MySQL user dinamai app_users agar tidak berbenturan dengan keyword PostgreSQL.
-- Aplikasi PHP mengakses lewat koneksi server database, bukan Supabase Auth / Data API.
BEGIN;
SET LOCAL TIME ZONE 'Asia/Jakarta';
SET LOCAL search_path = public;
${tables.join('\n\n')}
${extra}
${data.join('\n\n')}
${indexes.join('\n\n')}
${sequences}
${security}
REVOKE ALL ON SEQUENCE public.notifikasi_customer_id_notif_seq, public.chat_messages_id_seq FROM anon, authenticated;
COMMIT;
`;
fs.writeFileSync(path.join(root, 'db_rentalmobil_supabase.sql'), output);
console.log(`Generated db_rentalmobil_supabase.sql: ${names.length} tables, ${data.length} data statements.`);
